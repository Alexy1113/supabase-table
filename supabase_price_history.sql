-- Price history for Menuu Hinnad.
-- Run this in Supabase SQL Editor. Public visitors can only read this table;
-- the parser writes history using a server-side secret kept outside GitHub.

create table if not exists public.price_history (
    id bigint generated by default as identity primary key,
    dish_id text,
    restaurant_name text not null,
    dish_code text,
    dish_name text,
    price numeric(10, 2) not null check (price > 0),
    recorded_at timestamptz not null default now()
);

create index if not exists price_history_dish_id_recorded_at_idx
    on public.price_history (dish_id, recorded_at);

create index if not exists price_history_restaurant_code_recorded_at_idx
    on public.price_history (restaurant_name, dish_code, recorded_at);

alter table public.price_history enable row level security;

grant select on public.price_history to anon, authenticated;
grant insert, select on public.price_history to service_role;

drop policy if exists "Public can read price history" on public.price_history;

create policy "Public can read price history"
on public.price_history
for select
to anon, authenticated
using (true);
