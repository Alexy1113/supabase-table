-- Price history for Menuu Hinnad.
-- Run this in Supabase SQL Editor. Public visitors can only read this table;
-- the parser writes history using a server-side secret kept outside GitHub.

create table if not exists public.price_history (
    id bigint generated by default as identity primary key,
    dish_id text,
    restaurant_name text not null,
    dish_code text,
    dish_name text,
    price numeric(10, 2) not null check (price > 0),
    recorded_at timestamptz not null default now()
);

create index if not exists price_history_dish_id_recorded_at_idx
    on public.price_history (dish_id, recorded_at);

create index if not exists price_history_restaurant_code_recorded_at_idx
    on public.price_history (restaurant_name, dish_code, recorded_at);

alter table public.price_history enable row level security;

grant select on public.price_history to anon, authenticated;
grant insert, select on public.price_history to service_role;

drop policy if exists "Public can read price history" on public.price_history;

create policy "Public can read price history"
on public.price_history
for select
to anon, authenticated
using (true);

-- Seed one starting point for every existing product. This is the current
-- known price at last_updated, not a reconstruction of older price changes.
insert into public.price_history
    (dish_id, restaurant_name, dish_code, dish_name, price, recorded_at)
select
    d.id::text,
    d.restaurant_name,
    d.dish_code,
    d.dish_name,
    d.current_price,
    coalesce(d.last_updated, now())
from public.dishes d
where d.current_price is not null
  and d.current_price > 0
  and not exists (
      select 1
      from public.price_history h
      where h.restaurant_name = d.restaurant_name
        and (
            (d.dish_code is not null and h.dish_code = d.dish_code)
            or (d.dish_code is null and h.dish_id = d.id::text)
        )
  );
